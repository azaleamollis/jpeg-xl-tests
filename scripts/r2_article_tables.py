def refline(s, t, k, label, setting_fmt, note=""):
    c = D[(s, t, k)]
    sc = float(c["ssimulacra2_score"])
    st = "reached" if reached(c) else "target not reached, closest tried"
    w(f"| {ext(s)} | {t} | {label}{note} | {setting_fmt(c['setting'])} | {n(c['bytes'])} | {sc:.2f} | {st} |")
    ref.append(dict(image=ext(s), target=t, line=label + note, setting=setting_fmt(c["setting"]), bytes=c["bytes"], score=f"{sc:.2f}", status=st))


