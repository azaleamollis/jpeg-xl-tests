def reached(r):
    return r["status"] == "reached"


def lossy_table(stems, t, num, title):
    hdr = ["image"] + [c[1] for c in cols]
    rows_md, rows_csv, sc_md, sc_csv = [], [], [], []
    for s in stems:
        cells = {k: D[(s, t, k)] for k, _ in cols}
        jp = [k for k in ("JPEG", "MOZ420") if reached(cells[k])] or ["JPEG", "MOZ420"]
        base_k = min(jp, key=lambda k: int(cells[k]["bytes"]))
        base = int(cells[base_k]["bytes"])
        md_row = [ext(s)]
        csv_row = {"image": ext(s), "baseline_format": dict(cols)[base_k], "baseline_bytes": base}
        sc_row = [ext(s)]
        sc_csv_row = {"image": ext(s)}
        for k, lab in cols:
            c = cells[k]
            b = int(c["bytes"])
            sc = float(c["ssimulacra2_score"])
            mark = "" if reached(c) else f" **target not reached, closest score {sc:.2f}**"
            if k in ("JPEG", "MOZ420"):
                txt = (f"**{n(b)}**" if k == base_k else n(b)) + mark
                csv_row[lab + " bytes"] = b
                csv_row[lab + " pct_of_baseline"] = 100 if k == base_k else pct(b, base)
            else:
                txt = f"{n(b)} ({pct(b, base)}%)" + mark
                csv_row[lab + " bytes"] = b
                csv_row[lab + " pct_of_baseline"] = pct(b, base)
            csv_row[lab + " setting"] = "q" + c["setting"]
            csv_row[lab + " score"] = f"{sc:.2f}"
            csv_row[lab + " status"] = c["status"]
            md_row.append(txt)
            sc_row.append(f"{sc:.2f}" + ("" if reached(c) else " (not reached)"))
            sc_csv_row[lab] = f"{sc:.2f}"
            sc_csv_row[lab + " status"] = c["status"]
        rows_md.append(md_row)
        rows_csv.append(csv_row)
        sc_md.append(sc_row)
        sc_csv.append(sc_csv_row)
    w(f"### Table {num}: {title}\n")
    w("Cells are bytes of the full encoded file. **Bold** = the smaller of the two JPEG columns = the baseline for that row; WebP, AVIF and JXL cells show bytes and (size as % of the baseline, rounded half up to a whole percent). Quality settings are in the CSV copy.\n")
    w("| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr))
    for r in rows_md:
        w("| " + " | ".join(r) + " |")
    w(f"\n**SSIMULACRA 2 score of every cell in Table {num}** (target {t}, accepted {t-1} to {t+1}):\n")
    w("| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr))
    for r in sc_md:
        w("| " + " | ".join(r) + " |")
    w("")
    files[f"article_table{num}_lossy{t}.csv"] = rows_csv
    files[f"article_scores_{t}.csv"] = sc_csv


