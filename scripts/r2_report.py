FMTS = ["JPEG", "MOZ", "WebP", "AVIF", "JXL"]
n = lambda v: f"{int(v):,}"


def cell(stem, fmt, t, detail=False):
    if stem in ALPHA_IMAGES and fmt in ("JPEG", "MOZ"):
        return "-" if detail else "skipped (real transparency)"
    r = r1[(stem, fmt)] if (t == 70 and fmt != "MOZ") else r2[(stem, fmt, str(t))]
    q = r.get("quality", r.get("setting"))
    if detail:
        s = f"q{q} / {float(r['score']):.2f} / {r['iterations']}"
        return s if r["status"] == "reached" else s + " **(not reached)**"
    if r["status"] == "reached":
        return n(r["bytes"])
    return f"NOT REACHED (closest tried: q{q}, score {float(r['score']):.2f}, {n(r['bytes'])} B)"


def main_table(t):
    h = "| image | credit | notes (from manifest.csv) | " + " | ".join(LABEL[f] for f in FMTS) + " |\n|---|---|---|" + "---|" * len(FMTS)
    rows = []
    for stem in IMAGES:
        m = man[stem + "." + EXT_OF[stem]]
        rows.append(f"| {stem}.{EXT_OF[stem]} | {m['credit']}; {m['license']} | {m['notes']} | " +
                    " | ".join(cell(stem, f, t) for f in FMTS) + " |")
    return h + "\n" + "\n".join(rows)


def detail_table(t):
    h = "| image | " + " | ".join(LABEL[f] for f in FMTS) + " |\n|---|" + "---|" * len(FMTS)
    return h + "\n" + "\n".join(f"| {s}.{EXT_OF[s]} | " + " | ".join(cell(s, f, t, True) for f in FMTS) + " |" for s in IMAGES)


